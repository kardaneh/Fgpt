    def parse_fortran_file(self, file_path):
        """
        Parses a Fortran source file and returns its Abstract Syntax Tree (AST).

        Parameters:
        -----------
        file_path : str
            Path to the Fortran source file to be parsed.

        Returns:
        --------
        parse_tree : fparser.two.Fortran2008.Program
            The root of the abstract syntax tree (AST) generated by fparser.

        Raises:
        -------
        Exception
            If parsing fails due to invalid syntax or I/O issues.
        """
        try:
            reader = FortranFileReader(file_path, ignore_comments=False)
            parse_tree = self.parser(reader)
            self.logger.info("Successfully parsed file:\n%s", file_path)
            return parse_tree
        except Exception as e:
            self.logger.error("Failed to parse file:\n%s\nError: %s", file_path, e)
            raise

    def parse_fortran_string(self, string):
        """
        Parses a Fortran code snippet provided as a string and returns its AST.

        Parameters:
        -----------
        string : str
            A string containing valid Fortran source code.

        Returns:
        --------
        parse_tree : fparser.two.Fortran2008.Program
            The root of the AST representing the parsed code.

        Raises:
        -------
        Exception
            If the parsing fails due to invalid syntax or other errors.
        """
        try:
            reader = FortranStringReader(string, ignore_comments=False)
            parse_tree = self.parser(reader)
            self.logger.info(f"Successfully parsed string!")
            return parse_tree
        except Exception as e:
            self.logger.error(f"Failed to parse string, Error: {e}")
            raise

    def parse_fortran_statement(self, stmt_str):
        """
        Parses a single Fortran statement and returns its corresponding fparser AST node.

        Parameters:
        -----------
        stmt_str : str
            A single line or statement of Fortran code (e.g., an assignment, loop, etc.).

        Returns:
        --------
        node : fparser.two.base.Base
            The fparser AST node representing the parsed statement.

        Notes:
        ------
        - Wraps the statement inside a dummy program (with `program foo ... end`) to ensure it's valid Fortran.
        - This approach allows fparser to treat the input as a complete unit for parsing.
        - Filters out the program start and end lines to return only the actual statement node.
        - Useful for identifying what kind of AST node a statement maps to in `fparser.two.Fortran2003`.

        Raises:
        -------
        Exception
            If the statement cannot be parsed.
        """
        cleaned_stmt = textwrap.dedent(stmt_str).strip()
        code =  f"program foo\n{cleaned_stmt}\nend"
        try:
            reader = FortranStringReader(code, ignore_comments=True)
            parse_tree = self.parser(reader)
            for node in parse_tree.children:
                for child in node.content:
                    if not isinstance(child, F23.Program_Stmt) and not isinstance(child, F23.End_Program_Stmt):
                        self.logger.info("Successfully parsed statement:\n%s", child.tostr())
                        return child
            self.logger.warning(f"No valid statements found in: {stmt_str}")
            return None
        except Exception as e:
            self.logger.error("Failed to parse statement:\n%s\nError: %s", stmt_str, e)
            raise

    def parse_fortran_comment(self, stmt_str):
        """
        Parses a Fortran comment and returns the corresponding fparser comment node.

        Parameters:
        -----------
        stmt_str : str
            A single line Fortran comment (e.g., '! this is a comment').

        Returns:
        --------
        node : fparser.two.utils.Comment
            The fparser AST node representing the comment.

        Notes:
        ------
        - The comment is wrapped in a dummy program block for parsing context.
        - `ignore_comments=False` is required to ensure comments are preserved.
        - Walks the parsed tree to extract the comment node.
        - If no valid comment node is found, it raises a runtime error.

        Raises:
        -------
        RuntimeError
            If the comment could not be parsed or extracted.
        """
        cleaned_stmt = textwrap.dedent(stmt_str).strip()
        code = f"program foo\n{cleaned_stmt}\nend"
        try:
            reader = FortranStringReader(code, ignore_comments=False)
            parse_tree = self.parser(reader)
            for node in parse_tree.children:
                if not hasattr(node, 'content'):
                    continue
                for child in node.content:
                    if not isinstance(child, F23.Program_Stmt) and not isinstance(child, F23.End_Program_Stmt):
                        comment_node = child.children[0].children[0]
                        self.logger.info("Successfully parsed comment:\n%s", comment_node.tostr())
                        return comment_node
        except Exception as e:
            self.logger.error("Failed to parse comment:\n%s\nError: %s", stmt_str, e)
            raise

    def find_enclosing_parent(self, node, parent_type):
        """
        Traverse up the AST to find the first parent of a given type.

        Parameters
        ----------
        node : fparser.two.Fortran2003.Base
            The starting AST node from which to begin the upward search.
        parent_type : type
            The type of the parent node to search for, such as
            `fparser.two.Fortran2003.Subroutine_Subprogram` or
            `fparser.two.Fortran2003.Function_Subprogram`.

        Returns
        -------
        parent_type or None
            The first ancestor node of the specified type if found, otherwise None.

        Raises
        ------
        None
            This function does not raise, but logs errors internally if encountered.

        Notes
        -----
        - Traverses the `.parent` attributes of the AST nodes upward.
        - Useful for locating the containing Fortran construct (e.g., subroutine, function).
        - Depends on the AST nodes having correctly set `.parent` references.
        """
        try:
            while node is not None:
                if isinstance(node, parent_type):
                    return node
                node = getattr(node, 'parent', None)
            return None
        except Exception as e:
            self.logger.error(f"Error finding enclosing parent of type {parent_type.__name__}: {e}")
            return None

    def initiate_empty_routine(self, subroutine_name,  bin_filename="dummy.bin", routine_name="read_dummy"):
        """
        Generates a dummy Fortran subroutine with an open statement and a print,
        then parses and returns its AST node.

        Parameters:
        -----------
        subroutine_name : str
            The name to be used in the dummy subroutine's printed message and file path.

        Returns:
        --------
        subroutine_node : fparser.two.Fortran2003.Subroutine_Subprogram
            The root AST node representing the generated subroutine.

        Notes:
        ------
        - The dummy subroutine includes:
            - An `open` statement opening a binary file.
            - A write (print) statement to indicate execution.
        - The file path is constructed using `self.benchmark_dir` and the subroutine name.
        - Useful as a placeholder routine during transformation or benchmarking.
        - Parses the generated code using `FortranStringReader` and returns the subroutine AST node.
    
        Raises:
        -------
        Exception
            If the subroutine code cannot be parsed.
        """
        try:
            code_template = f"""
            subroutine {routine_name}()
                open(unit=1363, file='{self.benchmark_dir}/{subroutine_name}/{bin_filename}', form='unformatted', status='old')
                write(*,*) '--- inside the {routine_name} routine for {subroutine_name} ---'
            end subroutine {routine_name}
            """
            reader = FortranStringReader(code_template, ignore_comments=True)
            parse_tree = self.parser(reader)
            return parse_tree.children[0]
        except Exception as e:
            self.logger.error(f"Failed to generate Fortran code for routine {subroutine_name}, Error: {e}")
            raise

    def separate_entity_declarations(self, declaration_stmt):
        """
        Splits a combined Fortran type declaration statement into separate declarations,
        one for each variable.

        Parameters:
        -----------
        declaration_stmt : fparser.two.Fortran2003.Type_Declaration_Stmt
            A parsed Fortran declaration statement, possibly declaring multiple variables.

        Returns:
        --------
        new_decl : list of fparser.two.Fortran2003.Type_Declaration_Stmt
            A list of declaration statements, each declaring exactly one variable.

        Notes:
        ------
        - Preserves the left part (type, kind, dimension, intent, etc.).
        - Separates the variable names to create one declaration per variable.
        - Useful in code transformations that require granular control of declarations.
        """
        try:
            left_part = []
            right_part = []
            for child in declaration_stmt.children:
                if child==None:
                    continue
                if not isinstance(child, F23.Entity_Decl_List):
                    left_part.append(child.tostr())
                if isinstance(child, F23.Entity_Decl_List):
                    for child_child in walk(child, F23.Entity_Decl):
                        right_part.append(child_child.string)

            left_part_merged = ', '.join([name for name in left_part])
            new_decl = []
            for variable in right_part:
                decl = f"{left_part_merged} :: {variable}"
                new_decl.append(F23.Type_Declaration_Stmt(decl))
            return new_decl
        except Exception as e:
            self.logger.error("An error occurred during separation of variables: %s", e)
            raise

    def add_entity_to_declaration(self, declaration_stmt, var_modif):
        """
        Modifies a Fortran declaration by appending new variables (with _copy suffix)
        for those listed in var_modif.

        Parameters:
        -----------
        declaration_stmt : fparser.two.Fortran2003.Type_Declaration_Stmt
            The original Fortran declaration statement.

        var_modif : list of str
            A list of variable names for which new suffixed variables should be added.

        Returns:
        --------
        new_decl : fparser.two.Fortran2003.Type_Declaration_Stmt
            A new declaration statement including the original and modified variables.

        Notes:
        ------
        - Preserves the left-hand part (e.g., REAL(KIND=f64), INTENT(OUT)).
        - Duplicates any variable found in var_modif, adding a _copy version.
        - Useful for creating CPU/GPU variants of variables in transformed code.
        """
        try:
            left_part = []
            right_part = []
            for child in declaration_stmt.children:
                if child==None:
                    continue
                if not isinstance(child, F23.Entity_Decl_List):
                    left_part.append(child.tostr())
                if isinstance(child, F23.Entity_Decl_List):
                    for child_child in walk(child, F23.Entity_Decl):
                        right_part.append(child_child.string)
                        if child_child.string in var_modif:
                            right_part.append(child_child.string+'_copy')

            left_part_merged = ', '.join([name for name in left_part])
            right_part_merged = ', '.join([name for name in right_part])
            decl = f"{left_part_merged} :: {right_part_merged}"
            new_decl = F23.Type_Declaration_Stmt(decl)
            return new_decl
        except Exception as e:
            self.logger.error("An error occurred during adding an entity to a declaration: %s", e)
            raise

    def separate_entity_allocation(self, allocate_stmt):
        """
        Separates a compound Fortran ALLOCATE statement into multiple individual allocate statements,
        one for each variable.

        Parameters:
        -----------
        allocate_stmt : fparser.two.Fortran2003.Allocate_Stmt
            A parsed allocate statement, potentially allocating multiple variables.

        Returns:
        --------
        new_allocation : list of fparser.two.Fortran2003.Allocate_Stmt
            A list of new allocate statements, each allocating a single variable.

        Notes:
        ------
        - Also preserves optional allocation options (e.g., `stat=istat`).
        - Supports both Fortran 2003 and Fortran 2008 AST types.
        - Useful when tools need one allocation per line for readability or instrumentation.

        Raises:
        -------
        Exception
            If parsing or transformation fails.
        """
        try:
            lst = []
            opt = None

            for child in allocate_stmt.children:
                if child is None:
                    continue
                if isinstance(child, F23.Allocation_List) or isinstance(child, F28.Allocation_List):
                    for grandchild in child.children:
                        lst.append(grandchild.tostr())
                elif isinstance(child, F23.Alloc_Opt_List) or isinstance(child, F28.Alloc_Opt_List):
                    for grandchild in child.children:
                        opt = grandchild.tostr()

            new_allocation = []
            for variable in lst:
                if opt is not None:                                                                                                              
                    allocation = f"allocate({variable}, {opt})"                                      
                else:                                                                                  
                    allocation = f"allocate({variable})"   

                new_allocation.append(F23.Allocate_Stmt(allocation))

            self.logger.info("Successfully generated allocation statements")
            return new_allocation
        except Exception as e:
            self.logger.error(f"Failed to generate allocation statements, Error: {e}")
            raise

    def add_entity_to_allocation(self, allocate_stmt, var_modif, openacc=False):
        """
        Wraps allocation statements with `.not. allocated(...)` condition and adds
        suffixed allocations (e.g., `_copy`) for variables in var_modif.

        Parameters:
        -----------
        allocate_stmt : fparser.two.Fortran2003.Allocate_Stmt
            A parsed allocate statement, potentially allocating multiple variables.

        var_modif : list of str
            A list of variable names that require shadow allocation (e.g., with '_copy' suffix).

        Returns:
        --------
        new_allocation : list of fparser.two.statements.If_Construct
            A list of AST nodes, each wrapping allocation in a conditional check.

        Notes:
        ------
        - Wraps each allocation inside an `if (.not. allocated(...)) then` block.
        - If variable is in var_modif, creates a duplicate allocation for `<var>_copy`.
        - Prevents redundant allocations at runtime and supports CPU/GPU memory handling.

        Raises:
        -------
        Exception
            If generation or parsing of statements fails.
        """
        try:
            new_allocation = []
            for child in allocate_stmt.children:
                if child is None:
                    continue
                if isinstance(child, F23.Allocation_List) or isinstance(child, F28.Allocation_List):
                    for grandchild in child.children:
                        allocate_name = grandchild.children[0].tostr()
                        code = f"if(.not. allocated({allocate_name}))then\n{allocate_stmt.tostr()}\nend if"
                        new_allocation.append(self.parse_fortran_statement(code))
                        if allocate_name in var_modif:
                            if openacc:
                                allocate_name_add = allocate_name + '_copy'
                                allocation = re.sub(rf'\b{allocate_name}\b', allocate_name_add, allocate_stmt.tostr())
                                code = f"if(.not. allocated({allocate_name_add}))then\n{allocation}\nend if"
                                new_allocation.append(self.parse_fortran_statement(code))
            self.logger.info("Successfully generated allocation statements")
            return new_allocation
        except Exception as e:
            self.logger.error(f"Failed to generate allocation statements, Error: {e}")
            raise

    def map_declaration(self, implicit_dec, explicit_dec=None, dimensions=None):
        """
        Maps an assumed-shape or partially defined Fortran declaration (e.g. DIMENSION(:))
        to a fully explicit declaration (e.g. DIMENSION(kjpindex)).

        Parameters:
        -----------
        implicit_dec : fparser.two.Fortran2003.Type_Declaration_Stmt
            The original implicit declaration, typically with DIMENSION(:) or missing shape info.

        explicit_dec : fparser.two.Fortran2003.Type_Declaration_Stmt, optional
            A full declaration used to infer shape (when `dimensions` is not explicitly given).

        dimensions : str, optional
            A comma-separated string of dimensions (e.g. "kjpindex, nlev") to override shape detection.

        Returns:
        --------
        parsed_decl : fparser.two.Fortran2003.Type_Declaration_Stmt
            A new, fully formed declaration statement with mapped shape.

        Raises:
        -------
        ValueError if the variable type, name, or shape are missing or cannot be inferred.
        Exception if parsing the constructed declaration fails.
        """
        try:
            if walk(implicit_dec, F23.Intrinsic_Type_Spec):
                type_and_attributes = walk(implicit_dec, F23.Intrinsic_Type_Spec)[0].tostr()
            else:
                raise ValueError("variable type is not present!")
            
            if walk(implicit_dec, F23.Entity_Decl):
                #array_names = [child.children[0].tostr() for child in walk(implicit_dec, F23.Entity_Decl)]
                array_name = walk(implicit_dec, F23.Entity_Decl)[0].children[0].tostr()
                #array_name = ', '.join([name for name in  array_names])
            else:
                raise ValueError("variable name is not present!")
            
            if dimensions is None:
                assert explicit_dec is not None, "explicit_dec must be provided when assumed_shape is not None."
                if walk(explicit_dec, F23.Explicit_Shape_Spec):
                    shape = []
                    for dim in walk(explicit_dec, F23.Explicit_Shape_Spec):
                        shape.append(dim.tostr())
                    dimensions = ', '.join([name for name in shape])
                else:
                    raise ValueError("array shape is not present!")
            
            if walk(implicit_dec, F23.Intent_Attr_Spec):
                intent_attr = walk(implicit_dec, F23.Intent_Attr_Spec)[0].tostr()
                new_decl = f"{type_and_attributes}, DIMENSION({dimensions}), {intent_attr} :: {array_name}"
            else:
                new_decl = f"{type_and_attributes}, DIMENSION({dimensions}) :: {array_name}"
            
            self.logger.info(f"Mapped declaration: {new_decl}")
            parsed_decl = F23.Type_Declaration_Stmt(new_decl)
            return parsed_decl
        except Exception as e:
            self.logger.error(f"Failed to map declaration, Error: {e}")
            raise

    def combine_allocate_declaration(self, variable_declarations):
        """
        Combines a type declaration and an ALLOCATE statement into a single, explicit
        Fortran declaration with fixed dimensions.

        Parameters:
        -----------
        variable_declarations : list
            A list of two AST nodes: one must be a Type_Declaration_Stmt,
            the other an Allocate_Stmt.

        Returns:
        --------
        parsed_decl : fparser.two.Fortran2003.Type_Declaration_Stmt
            A combined type declaration statement with explicit shape.

        Raises:
        -------
        ValueError
            If shape or type/name information cannot be extracted.
        """
        try:
            for item in variable_declarations:
                if isinstance(item, F23.Allocate_Stmt):
                    if walk(item, F23.Allocate_Shape_Spec):
                        shape = []
                        for dim in walk(item, F23.Allocate_Shape_Spec):
                            shape.append(dim.tostr())
                        dimensions = ', '.join([name for name in shape])
                    else:
                        raise ValueError("allocarion shape is not present!")
                elif isinstance(item, F23.Type_Declaration_Stmt):
                    if walk(item, F23.Intrinsic_Type_Spec):
                        type_and_attributes = walk(item, F23.Intrinsic_Type_Spec)[0].tostr()
                    else:
                        raise ValueError("variable type is not present!")
                    if walk(item, F23.Entity_Decl):
                        array_name = walk(item, F23.Entity_Decl)[0].children[0].tostr()
                    else:
                        raise ValueError("variable name is not present!")
                    if walk(item, F23.Explicit_Shape_Spec_List):
                        shape = []
                        for dim in walk(item, F23.Explicit_Shape_Spec_List):
                            shape.append(dim.tostr())
                        dimensions = ', '.join([name for name in shape])
                else:
                    raise ValueError('Unrecognized statement')
            
            combined_statement = f"{type_and_attributes}, DIMENSION({dimensions}) :: {array_name}"
            self.logger.info(f"Combined statement: {combined_statement}")
            parsed_decl = F23.Type_Declaration_Stmt(combined_statement)
            return parsed_decl
        except Exception as e:
            self.logger.error(f"Failed to combine allocate and declaration, Error: {e}")
            raise

    def break_allocatable_declaration(self, declaration_stmt):

        try:
            result = {}
            # Extract type and attributes
            if walk(declaration_stmt, F23.Intrinsic_Type_Spec):
                type_and_attributes = walk(declaration_stmt, F23.Intrinsic_Type_Spec)[0].tostr()
            else:
                raise ValueError("Variable type is not present!")

            # Extract variable name
            for entity_decl in walk(declaration_stmt, F23.Entity_Decl):
                array_name = entity_decl.children[0].tostr()

                # Extract dimensions from explicit shape specification
                dimensions = []
                if walk(declaration_stmt, F23.Explicit_Shape_Spec_List):
                    explicit_shape_list = walk(declaration_stmt, F23.Explicit_Shape_Spec_List)[0]
                    for dim in explicit_shape_list.children:
                        dimensions.append(dim.tostr())
                    rank = len(dimensions)

                    # Create allocatable declaration with rank specification using colons
                    colons = ', '.join([':'] * rank)
                    allocatable_decl_str = f"{type_and_attributes}, ALLOCATABLE, DIMENSION({colons}) :: {array_name}"
                    self.logger.info(f"Allocatable declaration: {allocatable_decl_str}")
                    allocatable_decl = F23.Type_Declaration_Stmt(allocatable_decl_str)

                    # Create allocate statement with dimensions
                    dim_str = ', '.join(dimensions)
                    allocate_stmt_str = f"ALLOCATE({array_name}({dim_str}))"
                    self.logger.info(f"Allocate statement: {allocate_stmt_str}")
                    allocate_stmt = F23.Allocate_Stmt(allocate_stmt_str)
                    result[array_name] = [allocatable_decl, allocate_stmt]
                else:
                     result[array_name] = [declaration_stmt]

            return result
        except Exception as e:
            self.logger.error(f"Failed to break declaration into allocatable, Error: {e}")
            raise

    def remove_intent_and_save(self, type_declaration_stmts):
        """
        Removes specific Fortran attributes such as INTENT, SAVE, and PUBLIC 
        from a list of type declaration statements.

        Parameters:
        -----------
        type_declaration_stmts : list of Fortran2003.Type_Declaration_Stmt
            A list of Fortran type declaration AST nodes to clean.

        Returns:
        --------
        cleaned_statements : list of Fortran2003.Type_Declaration_Stmt
            Modified declarations without INTENT, SAVE, or PUBLIC attributes.

        Notes:
        ------
        - Useful for extracting variable declarations from subroutines and 
        reusing them in contexts where INTENT or SAVE is not allowed.
        - Maintains DIMENSION, POINTER, ALLOCATABLE, and other attributes.
        - Skips any node that is not a Type_Declaration_Stmt.
        """
        exclude = ['SAVE', 'INTENT', 'PUBLIC']
        cleaned_statements = []
        try:
            for stmt in type_declaration_stmts:
                if not isinstance(stmt, F23.Type_Declaration_Stmt):
                    cleaned_statements.append(stmt)
                    continue
                left_part = []
                right_part = ""
                for child in stmt.children:
                    if isinstance(child, F23.Intrinsic_Type_Spec):
                        left_part.append(child.tostr())
                    elif isinstance(child, F28.Attr_Spec_List) or isinstance(child, F23.Attr_Spec_List):
                        for grandchild in child.children:
                            if not any(excl in grandchild.tostr() for excl in exclude):
                                left_part.append(grandchild.tostr())
                    elif isinstance(child, F23.Entity_Decl_List):
                        right_part = child.tostr()

                left_part_merged = ', '.join(left_part)
                cleaned_stmt_str = f"{left_part_merged} :: {right_part}"
                cleaned_stmt = F23.Type_Declaration_Stmt(cleaned_stmt_str)
                cleaned_statements.append(cleaned_stmt)
            self.logger.info("Successfully removed INTENT and SAVE attributes from statements")
            return cleaned_statements
        except Exception as e:
            self.logger.error(f"Failed to remove INTENT and SAVE attributes, Error: {e}")
            raise

    def out_module_fortran(self, subroutine_name):
        """
        Generates and parses a Fortran `module` containing globally defined 
        constants, variables, and a utility subroutine for initialization.

        This method programmatically creates a Fortran source code string that 
        defines:

        - A module named `module_global`
        - Parameter constants (e.g., `i_std`, `r_std`, array sizes)
        - Globally scoped scalar variables
        - A `declaration_initialization` subroutine that opens a binary file 
            associated with the given `subroutine_name`

        Parameters:
        -----------
        subroutine_name : str
            Name of the subroutine for which the global binary file path 
            is constructed. This name is inserted into the `OPEN` statement 
            to load `global.bin`.

        Returns:
        --------
        parse_tree : fparser.two.Fortran2003.Program
            The parsed AST representation of the module and its contents.

        Raises:
        -------
        Exception
            If the Fortran string fails to parse.

        Notes:
        ------
        This method is useful for generating boilerplate global Fortran modules 
        used in benchmarking, testing, or modular code generation. It ensures 
        consistency in parameters and supports I/O operations embedded within 
        global modules.
        """
        code = f"""
        module module_global_{subroutine_name}
        implicit none
        integer, parameter :: i_std = 4
        integer, parameter :: r_std = 8
        integer(kind = i_std), parameter :: nice = 8
        integer(kind = i_std), parameter :: nsnow=3
        integer(kind = i_std), parameter :: nslm=11
        integer(kind = i_std), parameter :: nvm = 15
        integer(kind = i_std), parameter :: nstm = 3
        integer(kind = i_std), parameter :: kjpindex = 4717
        integer                          :: ier
        integer(kind = i_std)            :: ic0, ic
        real(kind = r_std)               :: icr, start_time, stop_time
        contains
        end module module_global_{subroutine_name}
        """
        try:
            reader = FortranStringReader(code, ignore_comments=False)
            parse_tree = self.parser(reader)
            self.logger.info("Successfully parsed module code")
            return parse_tree
        except Exception as e:
            self.logger.error(f"Failed to parse module code, Error: {e}")
            raise

    def check_point(self, var, var_copy, info):
        """
        Generates and parses a Fortran `IF` block that performs a runtime check 
        to compare two variables: typically a GPU version and a CPU reference.

        The generated code compares either scalar or array variables using `.EQ.` 
        or `.EQV.` (for logical types), and provides diagnostic output if the 
        check fails — including max errors or mismatched values.

        Parameters:
        -----------
        var : str
            The name of the GPU or test version of the variable (e.g., 'a').
    
        var_copy : str
            The name of the CPU or reference version of the variable (e.g., 'a_copy').
    
        info : list of str
            A list of type/property descriptors, such as ['REAL', 'DIMENSION'] 
            or ['LOGICAL'], which guides the comparison logic:
        
            - If 'DIMENSION' is present, array comparison is used (with `ALL(...)`)
            - If 'LOGICAL' is present, `.EQV.` is used instead of `.EQ.`
            - Otherwise, scalar `.EQ.` comparison is performed

        Returns:
        --------
        code : fparser.two.Fortran2003.If_Construct
            The parsed AST of the generated Fortran comparison block.

        Notes:
        ------
        - Supports scalar and array types.
        - Supports LOGICAL and numeric comparisons.
        - Designed for automated testing or benchmarking frameworks to validate
            GPU/CPU equivalence.
        - Diagnostic printouts help locate mismatch severity and range.
        """

        if 'DIMENSION' in info:
            if 'LOGICAL' not in info:
                code_template = f"""
                IF (ALL({var} .EQ. {var_copy})) THEN
                    write(*,*) 'Test passed: All elements in {var}_comp are equal to {var_copy}.'
                ELSE
                    write(*,*) ''
                    write(*,*) 'Test failed: All elements in {var}_comp do not match {var_copy}.'
                    write(*,'(A, E25.16)') 'Maximum absolute error:',  maxval(abs({var} - {var_copy}))
                    write(*,'(A, 2E25.16)') 'Min and Max of {var}_comp:', minval({var}), maxval({var})
                    write(*,'(A, 2E25.16)') 'Min and Max of {var_copy}:', minval({var_copy}), maxval({var_copy})
                    write(*,*) ''
                ENDIF
                """
            else:
                code_template = f"""
                IF (ALL({var} .EQV. {var_copy})) THEN
                    write(*,*) 'LOGICAL EQV test passed: All elements in {var}_comp are equal to {var_copy}.'
                ELSE
                    write(*,*) ''
                    write(*,*) 'LOGICAL EQV test failed: Not all elements in {var}_comp match {var_copy}.'
                    write(*,*) ''
                ENDIF
                """
        else:
            if 'LOGICAL' not in info:
                code_template = f"""
                IF ({var} .EQ. {var_copy}) THEN
                    write(*,*) 'Test passed: {var}_comp is equal to {var_copy}.'
                ELSE
                    write(*,*) ''
                    write(*,*) 'Test failed: {var}_comp does not match {var_copy}.'
                    write(*,'(A, E25.16)') 'Absolute error:', abs({var} - {var_copy})
                    write(*,'(A, 2E25.16)') '{var}_comp:', {var}
                    write(*,'(A, 2E25.16)') '{var_copy}:', {var_copy}
                    write(*,*) ''
                ENDIF
                """
            else:
                code_template = f"""
                IF ({var} .EQV. {var_copy}) THEN
                    write(*,*) 'LOGICAL EQV test passed: {var}_comp is equal to {var_copy}.'
                ELSE
                    write(*,*) ''
                    write(*,*) 'LOGICAL EQV test failed: {var}_comp does not match {var_copy}.'
                    write(*,'(A, L1)') '{var}_comp:', {var}
                    write(*,'(A, L1)') '{var_copy}:', {var_copy}
                    write(*,*) ''
                ENDIF
                """
        code = self.parse_fortran_statement(code_template)

        return code

    def out_main_fortran(self):
        """
        Generates and parses a minimal Fortran `main` program.

        This method creates a simple Fortran program named `main` with:
    
        - An `implicit none` declaration to enforce explicit typing.
        - A basic print statement to indicate entry into the main program.
        - A `contains` section included to support the addition of internal
            subroutines if needed in future code generation.

        This stub is useful as a starting point for wrapping generated modules, 
        calling subroutines, or building up a driver program structure for testing 
        or benchmarking.

        Returns:
        --------
        parse_tree : fparser.two.Fortran2003.Program
            The parsed Abstract Syntax Tree (AST) of the generated main program.

        Raises:
        -------
        Exception
            If the Fortran source fails to parse.

        """
        code = """
        program main
        implicit none
        write(*,*)'--- inside the main program ---'
        contains
        end program main
        """
        try:
            reader = FortranStringReader(code, ignore_comments=False)
            parse_tree = self.parser(reader)
            self.logger.info("Successfully parsed main program code")
            return parse_tree
        except Exception as e:
            self.logger.error(f"Failed to parse main program code, Error: {e}")
            raise

